#!/usr/bin/env bash
# Expand pins.tsv (versions x templates), resolve every ref to image:tag@sha256:<index
# digest>, and write pins.hcl (consumed by docker-bake.hcl). Needs network, not a daemon.
# bash 3.2 compatible (macOS). Retries with backoff: Docker Hub rate-limits anonymous HEAD
# requests (HTTP 429); `docker login` raises the limit.
set -euo pipefail
cd "$(dirname "$0")/.."

out=pins.hcl
tmp=$(mktemp); cache=$(mktemp)
trap 'rm -f "$tmp" "$cache"' EXIT

resolve() { # ref -> digest (memoised: shared refs like distroless are fetched once)
  local ref=$1 d attempt
  d=$(awk -F'\t' -v r="$ref" '$1==r {print $2; exit}' "$cache")
  if [[ -z "$d" ]]; then
    for attempt in 1 2 3 4 5 6; do
      d=$(docker buildx imagetools inspect "$ref" --format '{{.Manifest.Digest}}' 2>/dev/null || true)
      [[ "$d" == sha256:* ]] && break
      echo "  retry $attempt for $ref (rate limited or not found)" >&2
      sleep $((attempt * 10))
    done
    [[ "$d" == sha256:* ]] || { echo "could not resolve $ref" >&2; exit 1; }
    printf '%s\t%s\n' "$ref" "$d" >>"$cache"
  fi
  echo "$d"
}

versions_of() { awk -F'\t' -v l="$1" '$1=="versions" && $2==l {for(i=3;i<=NF;i++) print $i}' pins.tsv; }

{
  echo "// GENERATED by scripts/update-pins.sh from pins.tsv - do not edit by hand."
  echo "// Digests are multi-arch index digests, so amd64 and arm64 stay in lockstep."
  echo
  echo 'variable "VERSIONS" {'
  echo '  default = {'
  awk -F'\t' '$1=="versions" {
        printf "    %s = [", $2
        for (i = 3; i <= NF; i++) printf "%s\"%s\"", (i > 3 ? ", " : ""), $i
        print "]"
      }' pins.tsv
  echo '  }'
  echo '}'
  echo
  echo 'variable "PINS" {'
  echo '  default = {'
} >"$tmp"

while IFS=$'\t' read -r key tmpl _; do
  [[ -z "${key// }" || "$key" == \#* || "$key" == versions ]] && continue
  lang=${key%%/*}; role=${key#*/}
  for v in $(versions_of "$lang"); do
    ref=${tmpl//\{v\}/$v}
    digest=$(resolve "$ref")
    printf '    "%s/%s/%s" = "%s@%s"\n' "$lang" "$v" "$role" "$ref" "$digest" >>"$tmp"
    echo "pinned $lang/$v/$role -> $ref@${digest:0:19}…" >&2
  done
done <pins.tsv

printf '  }\n}\n' >>"$tmp"
mv "$tmp" "$out"
trap 'rm -f "$cache"' EXIT
echo "wrote $out" >&2
